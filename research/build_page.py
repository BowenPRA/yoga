def norm(s):
    s = s.lower()
    s = s.replace(" ii", " two").replace(" 2", " two")
    s = re.sub(r"[^\w\sàáảãạăằắẳẵặâầấẩẫậèéẻẽẹêềếểễệìíỉĩịòóỏõọôồốổỗộơờớởỡợùúủũụưừứửữựỳýỷỹỵđ]", " ", s)
    return re.sub(r"\s+", " ", s).strip()


def check(sample, fn):
    t = transcripts.get(fn, {}).get("transcript", "")
    if not t:
        return ("", "not checked")
    a, b = norm(sample["text"]).replace(" ", ""), norm(t).replace(" ", "")
    if a == b:
        return ("ok", "says exactly the sample text")
    # tolerate the transcriber truncating or re-punctuating
    if b in a or a.startswith(b[: max(10, len(b) - 5)]):
        return ("ok", "matches (transcriber cut short)")
    if any(w in b for w in ["you are a", "speak ", "say exactly"]):
        return ("bad", "read the style prompt aloud")
    return ("warn", f"transcribed as: {t}")


def seconds(fn):
    s = transcripts.get(fn, {}).get("seconds")
    return f"{s:.0f}s" if s else ""


def esc(s):
    return html.escape(str(s), quote=True)


