def coach_card(title, sub, rec):
    res = rec.get("result") if isinstance(rec, dict) else rec
    if not res:
        return f'<div class="model"><h4>{esc(title)}</h4><p class="err">{esc(rec.get("error", "no result"))}</p></div>'
    changes = "".join(
        f'<li><span class="from">{esc(c["from"])}</span> <span class="arr">→</span> <span class="to">{esc(c["to"])}</span><div class="vi">{esc(c["why_vi"])}</div></li>'
        for c in res.get("changes", []))
    pron = "".join(
        f'<li><b>{esc(p["word"])}</b><div class="vi">{esc(p["tip_vi"])}</div></li>' for p in res.get("pronunciation", []))
    meta = ""
    if isinstance(rec, dict) and rec.get("usage"):
        u = rec["usage"]
        tok_in = u.get("promptTokenCount", 0)
        tok_out = u.get("candidatesTokenCount", 0) + u.get("thoughtsTokenCount", 0)
        meta = f'<div class="meta">{rec.get("seconds", "?")}s · {tok_in} tokens in, {tok_out} out (incl. thinking)</div>'
    return f"""
    <div class="model">
      <h4>{esc(title)}<small>{esc(sub)}</small></h4>
      <p class="natural">“{esc(res['natural'])}”</p>
      <ul class="changes">{changes}</ul>
      <div class="pron-h">Pronunciation</div>
      <ul class="pron">{pron}</ul>
      <p class="praise">{esc(res.get('praise_vi', ''))}</p>
      {meta}
    </div>"""


